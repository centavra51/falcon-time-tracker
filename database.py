"""SQLite locally; persistent PostgreSQL when DATABASE_URL is configured."""

import os
import sqlite3
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row

INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)


class PostgresConnection:
    """Adapt the application's fixed SQL statements to psycopg parameters."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=None):
        sql = sql.replace("UNICODE_LOWER", "LOWER").replace("?", "%s")
        return self.connection.execute(sql, params)

    def executescript(self, sql):
        sql = sql.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )
        for statement in sql.split(";"):
            if statement.strip():
                self.execute(statement)


@contextmanager
def open_database(sqlite_path):
    database_url = os.environ.get("DATABASE_URL")
    if database_url:
        with psycopg.connect(database_url, row_factory=dict_row, connect_timeout=10) as conn:
            yield PostgresConnection(conn)
        return

    if os.environ.get("VERCEL"):
        raise RuntimeError("Set DATABASE_URL to a persistent PostgreSQL database on Vercel.")

    conn = sqlite3.connect(sqlite_path, timeout=15)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA journal_mode = WAL")
    conn.create_function(
        "UNICODE_LOWER", 1,
        lambda value: value.casefold() if isinstance(value, str) else value,
        deterministic=True,
    )
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
